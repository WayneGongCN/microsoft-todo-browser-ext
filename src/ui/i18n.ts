/** 根据明确偏好或浏览器语言选择文案，喵~ */
export function messages(language: Preferences['language']): typeof en {
  return language === 'zh_CN' || (language === 'system' && chrome.i18n.getUILanguage().startsWith('zh'))
    ? zh
    : en;
}

export type Messages = typeof en;
